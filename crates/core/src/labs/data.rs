const fn r(low: f64, high: f64) -> Normal {
    Normal { low, high, female: None, below: false }
}
const fn sexes(male: (f64, f64), female: (f64, f64)) -> Normal {
    Normal { low: male.0, high: male.1, female: Some(female), below: false }
}
